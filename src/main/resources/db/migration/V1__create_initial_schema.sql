CREATE TABLE grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL
);

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL
);

CREATE TABLE cartao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_vencimento INTEGER NOT NULL,
    limite NUMERIC(15,2) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    proprietario VARCHAR(255) NOT NULL,
    status VARCHAR(1) NOT NULL
);

CREATE TABLE conta_fixa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_conta DATE NOT NULL,
    data_criacao TIMESTAMP(6) NOT NULL,
    descricao VARCHAR(255),
    gasto_recorrente BOOLEAN NOT NULL,
    status_pagamento VARCHAR(1) NOT NULL,
    tipo VARCHAR(1) NOT NULL,
    usuario_criacao VARCHAR(255) NOT NULL,
    valor NUMERIC(15,2) NOT NULL,
    id_categoria BIGINT NOT NULL,
    id_grupo BIGINT NOT NULL,
    CONSTRAINT fk_conta_fixa_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id),
    CONSTRAINT fk_conta_fixa_grupo FOREIGN KEY (id_grupo) REFERENCES grupo(id)
);

CREATE TABLE gastos_cartao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_compra DATE NOT NULL,
    data_criacao TIMESTAMP(6) NOT NULL,
    descricao VARCHAR(255),
    id_externo VARCHAR(255),
    origem VARCHAR(20),
    parcela INTEGER NOT NULL,
    quantidade_parcelas INTEGER NOT NULL,
    status VARCHAR(1) NOT NULL,
    usuario VARCHAR(255) NOT NULL,
    valor NUMERIC(15,2) NOT NULL,
    cartao_id BIGINT NOT NULL,
    categoria_id BIGINT,
    CONSTRAINT uk_gastos_cartao_id_externo UNIQUE (id_externo),
    CONSTRAINT ck_gastos_cartao_origem CHECK (origem IN ('MANUAL', 'PDF', 'OFX', 'XLSX')),
    CONSTRAINT fk_gastos_cartao_cartao FOREIGN KEY (cartao_id) REFERENCES cartao(id),
    CONSTRAINT fk_gastos_cartao_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id)
);

CREATE INDEX idx_gastos_cartao_data_compra ON gastos_cartao(data_compra);
CREATE INDEX idx_gastos_cartao_cartao ON gastos_cartao(cartao_id);
