
-- Sprint 2.0: pagamentos parciais e historico financeiro

-- 1. Tabela para registrar cada pagamento individualmente
CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    lancamento_id BIGINT NOT NULL,

    valor NUMERIC(15,2) NOT NULL,

    data_pagamento DATE NOT NULL,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_pagamento_lancamento
        FOREIGN KEY (lancamento_id)
        REFERENCES lancamento(id),

    CONSTRAINT ck_pagamento_valor
        CHECK (valor > 0),

    CONSTRAINT ck_pagamento_version
        CHECK (version >= 0)
);

CREATE INDEX idx_pagamento_lancamento
    ON pagamento(lancamento_id);

-- 2. Migrar os pagamentos existentes
