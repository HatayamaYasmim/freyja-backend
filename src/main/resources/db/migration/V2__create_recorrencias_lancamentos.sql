CREATE TABLE conta_recorrente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    valor_previsto NUMERIC(15,2) NOT NULL,
    periodicidade VARCHAR(20) NOT NULL,
    dia_vencimento INTEGER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_recorrente_grupo FOREIGN KEY (grupo_id) REFERENCES grupo(id),
    CONSTRAINT fk_recorrente_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id),
    CONSTRAINT ck_recorrente_valor CHECK (valor_previsto >= 0),
    CONSTRAINT ck_recorrente_dia CHECK (dia_vencimento BETWEEN 1 AND 31),
    CONSTRAINT ck_recorrente_periodicidade CHECK (periodicidade IN ('MENSAL', 'ANUAL')),
    CONSTRAINT ck_recorrente_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE INDEX idx_recorrente_grupo ON conta_recorrente(grupo_id);

CREATE TABLE lancamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_recorrente_id BIGINT,
    grupo_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    competencia DATE NOT NULL,
    vencimento DATE NOT NULL,
    valor_previsto NUMERIC(15,2) NOT NULL,
    valor_pago NUMERIC(15,2),
    data_pagamento DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    observacoes TEXT,
    CONSTRAINT fk_lancamento_recorrente FOREIGN KEY (conta_recorrente_id) REFERENCES conta_recorrente(id),
    CONSTRAINT fk_lancamento_grupo FOREIGN KEY (grupo_id) REFERENCES grupo(id),
    CONSTRAINT fk_lancamento_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id),
    CONSTRAINT ck_lancamento_competencia CHECK (EXTRACT(DAY FROM competencia) = 1),
    CONSTRAINT ck_lancamento_valores CHECK (valor_previsto >= 0 AND (valor_pago IS NULL OR valor_pago >= 0)),
    CONSTRAINT ck_lancamento_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO')),
    CONSTRAINT ck_lancamento_pagamento CHECK ((status = 'PAGO' AND valor_pago IS NOT NULL AND data_pagamento IS NOT NULL) OR (status <> 'PAGO' AND valor_pago IS NULL AND data_pagamento IS NULL))
);

CREATE UNIQUE INDEX uk_lancamento_recorrente_competencia ON lancamento(conta_recorrente_id, competencia) WHERE conta_recorrente_id IS NOT NULL;
CREATE INDEX idx_lancamento_grupo_competencia ON lancamento(grupo_id, competencia);
CREATE INDEX idx_lancamento_status_vencimento ON lancamento(status, vencimento);
